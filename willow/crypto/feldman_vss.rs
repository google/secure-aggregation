/// A secret Ristretto255 scalar in `F_l` (`PartialEq` delegates to constant-time `Scalar::eq`).
#[derive(Clone, PartialEq, Eq)]
pub struct SecretScalar(Scalar);

impl std::fmt::Debug for SecretScalar {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("SecretScalar([REDACTED])")
    }
}

impl SecretScalar {
    /// Wraps `scalar` in a `SecretScalar`. Kept `pub(crate)` because Feldman VSS publishes the
    /// unblinded constant-term commitment `C_0 = s * G`, which is computationally hiding only when
    /// `s` has high min-entropy (obtained via [`Self::random`] or
    /// [`RistrettoFeldmanVss::reconstruct`]).
    pub(crate) fn new(scalar: Scalar) -> Self {
        Self(scalar)
    }

    /// Samples a uniform `SecretScalar` in `F_l` (~252 bits of min-entropy).
    pub fn random<R: CryptoRng + ?Sized>(rng: &mut R) -> Self {
        Self(Scalar::random(rng))
    }

    /// Returns the canonical 32-byte little-endian encoding of this Ristretto255 scalar in `F_l`
    /// (matching `curve25519-dalek` `Scalar::as_bytes` for the 253-bit group order `l < 2^256`).
    pub fn as_bytes(&self) -> &[u8; 32] {
        self.0.as_bytes()
    }
}

/// A single Shamir/Feldman share `(i, f(i))` evaluated at a 1-based participant index `i`
/// (`NonZeroU32`) over `F_l` (`1 <= i <= u32::MAX < l`).
#[derive(Clone, PartialEq, Eq)]
pub struct Share {
    pub index: NonZeroU32,
    value: Scalar,
}

impl std::fmt::Debug for Share {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Share").field("index", &self.index).field("value", &"[REDACTED]").finish()
    }
}

impl Share {
    /// Constructs a `Share` from a 1-based `index` and field scalar `value`.
    pub(crate) fn new(index: NonZeroU32, value: Scalar) -> Self {
        Self { index, value }
    }
}

/// Public Feldman polynomial commitment `(C_0, C_1, ..., C_{t-1})` where `C_k = a_k * G`.
///
/// Each element `C_k` binds coefficient `a_k`, and the vector length `t` fixes the reconstruction
/// threshold (bounding the sharing polynomial to degree `< t`). [`FromProto`] validates and
/// decompresses all 32-byte `CompressedRistretto` points once at deserialization time.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct FeldmanCommitment {
    commitments: Vec<CompressedRistretto>,
    points: Vec<RistrettoPoint>,
}

impl FeldmanCommitment {
    /// Computes Feldman coefficient commitments `C_k = a_k * G` (for `k = 0..t-1`) using
    /// constant-time basepoint multiplication (`RistrettoPoint::mul_base`).
    fn from_coefficients(coeffs: &[Scalar]) -> Self {
        let points: Vec<RistrettoPoint> = coeffs.iter().map(RistrettoPoint::mul_base).collect();
        let commitments: Vec<CompressedRistretto> =
            points.iter().map(RistrettoPoint::compress).collect();
        Self { commitments, points }
    }

    /// Evaluates the committed polynomial in the group at `x = index`:
    /// `sum_{k=0}^{t-1} x^k * C_k = f(x) * G`.
    ///
    /// Uses variable-time multiscalar multiplication because both evaluation index `x` and
    /// commitments `C_k` are public; scalar powers `x^k` are computed iteratively in `F_l`.
    fn evaluate_at(&self, index: NonZeroU32) -> RistrettoPoint {
        let x = Scalar::from(index.get());
        let mut powers = Vec::with_capacity(self.points.len());
        let mut x_pow = Scalar::ONE;
        for _ in 0..self.points.len() {
            powers.push(x_pow);
            x_pow *= x;
        }
        RistrettoPoint::vartime_multiscalar_mul(powers.iter(), &self.points)
    }

    /// Returns the reconstruction threshold `t` (number of coefficient commitments
    /// `[C_0, ..., C_{t-1}]` for a sharing polynomial of degree `< t`).
    pub fn threshold(&self) -> usize {
        self.commitments.len()
    }
}

impl ToProto for Share {
    type Proto = FeldmanShareProto;

    fn to_proto(&self, _ctx: ()) -> Result<Self::Proto, StatusError> {
        let index = i32::try_from(self.index.get())
            .map_err(|_| status::invalid_argument("VSS share index exceeds i32::MAX"))?;
        Ok(proto!(FeldmanShareProto { index, value: self.value.as_bytes().to_vec() }))
    }
}

impl FromProto for Share {
    type Proto = FeldmanShareProto;

    fn from_proto(
        proto: impl AsView<Proxied = Self::Proto>,
        _ctx: (),
    ) -> Result<Self, StatusError> {
        let proto = proto.as_view();
        let index = u32::try_from(proto.index())
            .ok()
            .and_then(NonZeroU32::new)
            .ok_or_else(|| status::invalid_argument("VSS share index must be positive"))?;
        let arr: [u8; 32] = proto.value().try_into().map_err(|_| {
            status::invalid_argument("Feldman VSS share scalar byte slice must be exactly 32 bytes")
        })?;
        let opt: Option<Scalar> = Scalar::from_canonical_bytes(arr).into();
        let value = opt.ok_or_else(|| {
            status::invalid_argument("Non-canonical Ristretto255 scalar encoding (>= group order)")
        })?;
        Ok(Self::new(index, value))
    }
}

impl ToProto for FeldmanCommitment {
    type Proto = FeldmanCommitmentProto;

    fn to_proto(&self, _ctx: ()) -> Result<Self::Proto, StatusError> {
        Ok(proto!(FeldmanCommitmentProto {
            commitments: self.commitments.iter().map(|c| c.as_bytes().to_vec()),
        }))
    }
}

impl FromProto<u32> for FeldmanCommitment {
    type Proto = FeldmanCommitmentProto;

    fn from_proto(
        proto: impl AsView<Proxied = Self::Proto>,
        max_threshold: u32,
    ) -> Result<Self, StatusError> {
        if max_threshold == 0 {
            return Err(status::invalid_argument(
                "FeldmanCommitment max_threshold must be non-zero",
            ));
        }
        let proto = proto.as_view();
        let raw_commitments = proto.commitments();
        if raw_commitments.is_empty() || raw_commitments.len() > max_threshold as usize {
            return Err(status::invalid_argument(
                "FeldmanCommitment length must be in 1..=max_threshold",
            ));
        }
        let mut commitments = Vec::with_capacity(raw_commitments.len());
        let mut points = Vec::with_capacity(raw_commitments.len());
        for bytes in raw_commitments.iter() {
            let compressed = CompressedRistretto::from_slice(bytes).map_err(|_| {
                status::invalid_argument("FeldmanCommitment point must be exactly 32 bytes")
            })?;
            let pt = compressed.decompress().ok_or_else(|| {
                status::invalid_argument("Invalid compressed Ristretto255 point in commitment")
            })?;
            commitments.push(compressed);
            points.push(pt);
        }
        Ok(Self { commitments, points })
    }
}

// --- Internal Shamir polynomial helpers ---

/// Samples a random polynomial `[s, a_1, ..., a_{t-1}]` of degree `< threshold` over `F_l` with
/// constant term `a_0 = secret` and independent uniform coefficients `a_k <- F_l`.
fn sample_polynomial<R: CryptoRng + ?Sized>(
    secret: &SecretScalar,
    threshold: usize,
    rng: &mut R,
) -> Vec<Scalar> {
    let mut coeffs = Vec::with_capacity(threshold);
    coeffs.push(secret.0);
    for _ in 1..threshold {
        coeffs.push(Scalar::random(rng));
    }
    coeffs
}

/// Evaluates `f(x) = sum_{k=0}^{t-1} coeffs[k] * x^k` in `F_l` in constant time using Horner's
/// method.
fn evaluate_polynomial(coeffs: &[Scalar], x: Scalar) -> Scalar {
    let mut y = Scalar::ZERO;
    for coeff in coeffs.iter().rev() {
        y = y * x + coeff;
    }
    y
}

/// Reconstructs the constant term `f(0)` from `shares` via Lagrange interpolation at `x = 0`:
///   `f(0) = sum_{j=0}^{t-1} y_j * L_j(0)`, where `L_j(0) = prod_{m != j} x_m / (x_m - x_j)`.
///
/// Taking `&BTreeMap<NonZeroU32, Scalar>` enforces that every evaluation point `x_j` is non-zero
/// (`1 <= x_j <= u32::MAX < l`, since `l > 2^252`) and pairwise distinct (`x_m != x_j`).
fn lagrange_interpolate_at_zero(shares: &BTreeMap<NonZeroU32, Scalar>) -> Scalar {
    let t = shares.len();
    let mut numerators = Vec::with_capacity(t);
    let mut denominators = Vec::with_capacity(t);
    for (&idx_j, _) in shares {
        let x_j = Scalar::from(idx_j.get());
        let mut num = Scalar::ONE;
        let mut den = Scalar::ONE;
        for (&idx_m, _) in shares {
            if idx_m != idx_j {
                let x_m = Scalar::from(idx_m.get());
                num *= x_m;
                den *= x_m - x_j;
            }
        }
        numerators.push(num);
        denominators.push(den);
    }

    // `Scalar::invert_batch_alloc` requires non-zero inputs, which holds since `x_m != x_j` in
    // `F_l`.
    Scalar::invert_batch_alloc(&mut denominators);

    let mut secret = Scalar::ZERO;
    for (j, &y_j) in shares.values().enumerate() {
        let lagrange_coeff = numerators[j] * denominators[j];
        secret += y_j * lagrange_coeff;
    }
    secret
}

/// Ristretto255 implementation of [`VerifiableSecretSharing`] using Shamir secret sharing
/// and Feldman polynomial commitments.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct RistrettoFeldmanVss;

impl VerifiableSecretSharing for RistrettoFeldmanVss {
    type Secret = SecretScalar;
    type Share = Share;
    type Commitment = FeldmanCommitment;

    /// Samples a degree `< threshold` polynomial over `F_l` with constant term `secret`, commits
    /// to its coefficients (`C_k = a_k * G`), and evaluates shares at `i = 1..=num_shares`.
    fn split<R: CryptoRng + ?Sized>(
        &self,
        secret: &Self::Secret,
        threshold: u32,
        num_shares: u32,
        rng: &mut R,
    ) -> Result<(Self::Commitment, Vec<Self::Share>), StatusError> {
        if threshold == 0 || threshold > num_shares {
            return Err(status::invalid_argument(
                "Invalid (threshold, num_shares): require 1 <= threshold <= num_shares",
            ));
        }

        let coeffs = sample_polynomial(secret, threshold as usize, rng);
        let commitment = FeldmanCommitment::from_coefficients(&coeffs);

        let mut shares = Vec::with_capacity(num_shares as usize);
        for i in 1..=num_shares {
            let idx = NonZeroU32::new(i).unwrap();
            let y = evaluate_polynomial(&coeffs, Scalar::from(i));
            shares.push(Share::new(idx, y));
        }

        Ok((commitment, shares))
    }

    /// Verifies `y_i * G == sum_{k=0}^{t-1} i^k * C_k` in Ristretto255 (`mul_base` is
    /// constant-time on secret share scalar `y_i`).
    fn verify_share(&self, commitment: &Self::Commitment, share: &Self::Share) -> status::Status {
        let lhs = RistrettoPoint::mul_base(&share.value);
        let rhs = commitment.evaluate_at(share.index);

        if lhs == rhs {
            Ok(())
        } else {
            Err(status::invalid_argument("Feldman VSS share verification failed"))
        }
    }

    /// Verifies all supplied shares against `commitment` and recovers `s = f(0)` in `F_l` via
    /// Lagrange interpolation from the first `t` distinct shares.
    fn reconstruct(
        &self,
        commitment: &Self::Commitment,
        shares: &[Self::Share],
    ) -> Result<Self::Secret, StatusError> {
        let t = commitment.threshold();
        if shares.len() < t {
            return Err(status::invalid_argument("Insufficient shares to reconstruct secret"));
        }

        let mut seen = BTreeSet::new();
        let mut interpolation_shares = BTreeMap::new();
        for share in shares {
            if !seen.insert(share.index) {
                return Err(status::invalid_argument("Duplicate share index in reconstruct"));
            }
            self.verify_share(commitment, share)?;
            if interpolation_shares.len() < t {
                interpolation_shares.insert(share.index, share.value);
            }
        }

        Ok(SecretScalar::new(lagrange_interpolate_at_zero(&interpolation_shares)))
    }
}

