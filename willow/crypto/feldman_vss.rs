//! t-of-n Feldman Verifiable Secret Sharing (VSS) over Ristretto255.
//!
//! Implements [`VerifiableSecretSharing`] using Shamir polynomial secret sharing paired with
//! Feldman commitments over the prime-order Ristretto255 group generated by basepoint `G` of order
//! `l = 2^252 + 27742317777372353535851937790883648493`:
//! - A dealer splits a uniform secret `s` in `F_l` using a random polynomial of degree `< t`, `f(x)
//!   = s + sum_{k=1}^{t-1} a_k * x^k`, with `a_0 = s` and coefficients `a_1, ..., a_{t-1}` sampled
//!   independently and uniformly at random from `F_l`.
//! - The dealer publishes `t` coefficient commitments `C_k = a_k * G` (`k = 0..t-1`) and sends
//!   participant `i` (`1 <= i <= n`) the share `(i, y_i)` where `y_i = f(i) mod l`.
//! - Because `C_0 = s * G` is published unblinded (unlike Pedersen VSS), computational hiding
//!   relies on `s` being sampled uniformly from `F_l` (~252 bits of min-entropy) so `C_0` cannot be
//!   inverted by discrete-log search.
//!
//! # Constant-Time Properties
//! Operations on secret scalars and share values execute in constant time, whereas variable-time
//! operations are used only on public evaluation indices and public commitments.
//!
//! References:
//! - Paul Feldman, "A Practical Scheme for Non-Interactive Verifiable Secret Sharing", Proceedings
//!   of the 28th Annual Symposium on Foundations of Computer Science (FOCS), pp. 427-437, IEEE,
//!   1987 (doi:10.1109/SFCS.1987.4).
//! - Yi-Hsiu Chen and Yehuda Lindell, "Feldman's Verifiable Secret Sharing for a Dishonest
//!   Majority", IACR Communications in Cryptology (CiC), 1(1):16, 2024 (doi:10.62056/ak2isgvtw).

