    // --- Shamir secret-sharing tests (polynomial evaluation & Lagrange interpolation) ---

    #[gtest]
    fn test_shamir_split_and_reconstruct_subsets() -> GTestResult<()> {
        let mut rng = create_test_rng();
        let vss = RistrettoFeldmanVss;
        let secret = SecretScalar::random(&mut rng);

        let (commitment, shares) = vss.split(&secret, 3, 5, &mut rng)?;
        verify_eq!(commitment.threshold(), 3)?;
        verify_eq!(shares.len(), 5)?;

        // Any 3-share subset reconstructs the exact secret via Lagrange interpolation at x = 0.
        let subset_a = vec![shares[0].clone(), shares[1].clone(), shares[2].clone()];
        let subset_b = vec![shares[1].clone(), shares[3].clone(), shares[4].clone()];
        let subset_c = vec![shares[4].clone(), shares[2].clone(), shares[0].clone()];
        verify_eq!(vss.reconstruct(&commitment, &subset_a)?, secret)?;
        verify_eq!(vss.reconstruct(&commitment, &subset_b)?, secret)?;
        verify_eq!(vss.reconstruct(&commitment, &subset_c)?, secret)?;

        // Passing > t valid shares also reconstructs the exact secret.
        verify_eq!(vss.reconstruct(&commitment, &shares)?, secret)?;
        Ok(())
    }

    #[gtest]
    fn test_boundary_thresholds_and_large_committee() -> GTestResult<()> {
        let mut rng = create_test_rng();
        let vss = RistrettoFeldmanVss;
        // Covers (t=1, n=1), (t=1, n=5), (t=n=5), high-degree (t=15, n=100), and (t=10, n=1000).
        for &(t, n) in &[(1u32, 1u32), (1, 5), (5, 5), (15, 100), (10, 1000)] {
            let secret = SecretScalar::random(&mut rng);
            let (comm, shares) = vss.split(&secret, t, n, &mut rng)?;
            verify_eq!(shares.len(), n as usize)?;
            vss.verify_share(&comm, &shares[(n - 1) as usize])?;
            let tail_subset = &shares[(n - t) as usize..];
            verify_eq!(vss.reconstruct(&comm, tail_subset)?, secret)?;
        }
        Ok(())
    }

