    // --- Feldman verifiability & commitment-binding tests ---

    #[gtest]
    fn test_feldman_verify_share_rejects_tampered_share_and_swapped_index() -> GTestResult<()> {
        let mut rng = create_test_rng();
        let vss = RistrettoFeldmanVss;
        let secret = SecretScalar::random(&mut rng);
        let (commitment, shares) = vss.split(&secret, 3, 5, &mut rng)?;

        for share in &shares {
            vss.verify_share(&commitment, share)?;
        }

        // Tamper with share value (y_1 + 1 != f(1)).
        let mut bad_share = shares[0].clone();
        bad_share.value += Scalar::ONE;
        verify_that!(
            vss.verify_share(&commitment, &bad_share),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;

        // Even if bad_share is the (t+1)-th share passed to reconstruct, reconstruct must fail
        // fast because it verifies every supplied share against the commitment.
        let shares_with_bad_tail =
            vec![shares[0].clone(), shares[1].clone(), shares[2].clone(), bad_share];
        verify_that!(
            vss.reconstruct(&commitment, &shares_with_bad_tail),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;

        // Share evaluated at the wrong index (index 2 with value f(1)) is rejected.
        let swapped_index_share = Share::new(nz(2), shares[0].value);
        verify_that!(
            vss.verify_share(&commitment, &swapped_index_share),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;

        Ok(())
    }

    #[gtest]
    fn test_zero_share_evaluation_verifies_and_reconstructs() -> GTestResult<()> {
        let mut rng = create_test_rng();
        let vss = RistrettoFeldmanVss;

        // 1. Zero secret `s = 0` (`C_0 = O`): split, verify_share, and reconstruct over F_l.
        let zero_secret = SecretScalar::new(Scalar::ZERO);
        verify_eq!(zero_secret.as_bytes(), &[0u8; 32])?;
        let (zero_comm, zero_secret_shares) = vss.split(&zero_secret, 3, 5, &mut rng)?;
        verify_eq!(zero_comm.commitments[0], CompressedRistretto::default())?;
        for share in &zero_secret_shares {
            vss.verify_share(&zero_comm, share)?;
        }
        verify_eq!(vss.reconstruct(&zero_comm, &zero_secret_shares[..3])?, zero_secret)?;

        // 2. Zero higher-degree coefficient `a_{t-1} = 0` (`C_{t-1} = O` for t = 3,
        // f(x) = s + a_1 * x + 0 * x^2): 3-point Lagrange interpolation still recovers f(0) = s.
        let s = Scalar::from(7u64);
        let a1 = Scalar::from(19u64);
        let expected_secret = SecretScalar::new(s);
        let deg1_comm = FeldmanCommitment::from_coefficients(&[s, a1, Scalar::ZERO]);
        let deg1_shares: Vec<Share> = (1u32..=3)
            .map(|i| {
                let x = Scalar::from(i);
                Share::new(nz(i), s + a1 * x)
            })
            .collect();
        for share in &deg1_shares {
            vss.verify_share(&deg1_comm, share)?;
        }
        verify_eq!(vss.reconstruct(&deg1_comm, &deg1_shares)?, expected_secret)?;

        // 3. Deterministic t = 2 polynomial f(x) = s + (-s) * x over F_l so f(1) == 0 mod l
        // and f(2) == -s.
        let a1_neg = -s;
        let commitment = FeldmanCommitment::from_coefficients(&[s, a1_neg]);
        let share_1 =
            Share::from_proto(proto!(FeldmanShareProto { index: 1, value: vec![0u8; 32] }), ())?;
        let share_2 = Share::from_proto(
            proto!(FeldmanShareProto { index: 2, value: (-s).as_bytes().to_vec() }),
            (),
        )?;
        verify_eq!(share_1.to_proto(())?.value(), &[0u8; 32])?;

        vss.verify_share(&commitment, &share_1)?;
        vss.verify_share(&commitment, &share_2)?;
        verify_eq!(vss.reconstruct(&commitment, &[share_1.clone(), share_2])?, expected_secret)?;

        // For t = 1 (constant polynomial f(x) = s != 0), a zero share fails verification because
        // C_0 = s * G != O.
        let comm_t1 = FeldmanCommitment::from_coefficients(&[s]);
        verify_that!(
            vss.verify_share(&comm_t1, &share_1),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;

        Ok(())
    }

    #[gtest]
    fn test_forged_commitment_rejected() -> GTestResult<()> {
        let mut rng = create_test_rng();
        let vss = RistrettoFeldmanVss;
        let secret = SecretScalar::random(&mut rng);
        let (commitment, shares) = vss.split(&secret, 3, 5, &mut rng)?;
        let basepoint = RistrettoPoint::mul_base(&Scalar::ONE);

        // Perturbing the constant-term commitment C_0 -> C_0 + G while keeping honest shares
        // must fail verification and reconstruction.
        let mut forged_c0_proto = commitment.to_proto(())?;
        forged_c0_proto
            .commitments_mut()
            .set(0, (commitment.points[0] + basepoint).compress().as_bytes().to_vec());
        let forged_c0 = FeldmanCommitment::from_proto(forged_c0_proto, 10)?;
        verify_that!(
            vss.verify_share(&forged_c0, &shares[0]),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;
        verify_that!(
            vss.reconstruct(&forged_c0, &shares[..3]),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;

        // Perturbing a higher-degree coefficient commitment C_1 -> C_1 + G while keeping honest
        // shares must also fail verification and reconstruction.
        let mut forged_c1_proto = commitment.to_proto(())?;
        forged_c1_proto
            .commitments_mut()
            .set(1, (commitment.points[1] + basepoint).compress().as_bytes().to_vec());
        let forged_c1 = FeldmanCommitment::from_proto(forged_c1_proto, 10)?;
        verify_that!(
            vss.verify_share(&forged_c1, &shares[0]),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;
        verify_that!(
            vss.reconstruct(&forged_c1, &shares[..3]),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;

        Ok(())
    }

    #[gtest]
    fn test_proto_serialization_roundtrip_and_redacted_debug() -> GTestResult<()> {
        let mut rng = create_test_rng();
        let vss = RistrettoFeldmanVss;
        let secret = SecretScalar::random(&mut rng);
        let (commitment, shares) = vss.split(&secret, 3, 5, &mut rng)?;

        verify_true!(format!("{:?}", secret).contains("[REDACTED]"))?;
        verify_true!(format!("{:?}", shares[0]).contains("[REDACTED]"))?;

        let comm_proto = commitment.to_proto(())?;
        verify_eq!(comm_proto.commitments().len(), 3)?;
        verify_eq!(
            comm_proto.commitments().iter().next(),
            Some(commitment.commitments[0].as_bytes().as_slice())
        )?;
        let comm_roundtrip = FeldmanCommitment::from_proto(comm_proto, 10)?;
        verify_eq!(comm_roundtrip, commitment)?;

        let mut shares_roundtrip = Vec::with_capacity(shares.len());
        for share in &shares {
            let share_proto = share.to_proto(())?;
            verify_eq!(share_proto.index(), share.index.get() as i32)?;
            let decoded = Share::from_proto(share_proto, ())?;
            verify_eq!(&decoded, share)?;
            vss.verify_share(&comm_roundtrip, &decoded)?;
            shares_roundtrip.push(decoded);
        }
        verify_eq!(vss.reconstruct(&comm_roundtrip, &shares_roundtrip[..3])?, secret)?;
        Ok(())
    }

    #[gtest]
    fn test_share_from_proto_rejects_malformed_inputs() -> GTestResult<()> {
        let mut rng = create_test_rng();
        let vss = RistrettoFeldmanVss;
        let secret = SecretScalar::random(&mut rng);
        let (_commitment, shares) = vss.split(&secret, 3, 5, &mut rng)?;
        let valid_value = shares[0].to_proto(())?.value().to_vec();

        let zero_idx_proto = proto!(FeldmanShareProto { index: 0, value: valid_value.clone() });
        verify_that!(
            Share::from_proto(zero_idx_proto, ()),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;

        let neg_idx_proto = proto!(FeldmanShareProto { index: -1, value: valid_value.clone() });
        verify_that!(
            Share::from_proto(neg_idx_proto, ()),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;

        let high_idx_proto = proto!(FeldmanShareProto { index: 250, value: valid_value });
        let high_share = Share::from_proto(high_idx_proto, ())?;
        verify_eq!(high_share.index.get(), 250)?;

        let short_val_proto = proto!(FeldmanShareProto { index: 1, value: vec![1u8; 31] });
        verify_that!(
            Share::from_proto(short_val_proto, ()),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;

        let non_canonical_val_proto =
            proto!(FeldmanShareProto { index: 1, value: vec![0xFFu8; 32] });
        verify_that!(
            Share::from_proto(non_canonical_val_proto, ()),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;

        // Zero share scalar bytes are valid canonical scalars (possible evaluation for t >= 2).
        let zero_val_proto = proto!(FeldmanShareProto { index: 1, value: vec![0u8; 32] });
        let zero_share = Share::from_proto(zero_val_proto, ())?;
        verify_eq!(zero_share.to_proto(())?.value(), &[0u8; 32])?;
        Ok(())
    }

    #[gtest]
    fn test_commitment_from_proto_rejects_malformed_inputs() -> GTestResult<()> {
        let valid_pt_bytes = RistrettoPoint::mul_base(&Scalar::ONE).compress().to_bytes().to_vec();

        let zero_cap_proto =
            proto!(FeldmanCommitmentProto { commitments: [valid_pt_bytes.clone()] });
        verify_that!(
            FeldmanCommitment::from_proto(zero_cap_proto, 0),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;

        let empty_comm_proto = proto!(FeldmanCommitmentProto {});
        verify_that!(
            FeldmanCommitment::from_proto(empty_comm_proto, 10),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;

        let oversized_comm_proto = proto!(FeldmanCommitmentProto {
            commitments: (0..=10).map(|_| valid_pt_bytes.clone()),
        });
        verify_that!(
            FeldmanCommitment::from_proto(oversized_comm_proto, 10),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;

        let short_pt_comm_proto = proto!(FeldmanCommitmentProto { commitments: [vec![1u8; 31]] });
        verify_that!(
            FeldmanCommitment::from_proto(short_pt_comm_proto, 10),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;

        // Canonical identity point `[0u8; 32]` (`O = 0 * G`) in `C_0` (`s = 0`) or higher-degree
        // `C_k` (`a_k = 0`) is accepted and round-trips through `to_proto` / `from_proto`.
        let identity_comm_proto =
            proto!(FeldmanCommitmentProto { commitments: [vec![0u8; 32], valid_pt_bytes.clone()] });
        let identity_comm = FeldmanCommitment::from_proto(identity_comm_proto, 10)?;
        verify_eq!(FeldmanCommitment::from_proto(identity_comm.to_proto(())?, 10)?, identity_comm)?;

        let leading_identity_comm_proto =
            proto!(FeldmanCommitmentProto { commitments: [valid_pt_bytes, vec![0u8; 32]] });
        let leading_identity_comm = FeldmanCommitment::from_proto(leading_identity_comm_proto, 10)?;
        verify_eq!(
            FeldmanCommitment::from_proto(leading_identity_comm.to_proto(())?, 10)?,
            leading_identity_comm
        )?;

        let invalid_curve_comm_proto =
            proto!(FeldmanCommitmentProto { commitments: [vec![0xFFu8; 32]] });
        verify_that!(
            FeldmanCommitment::from_proto(invalid_curve_comm_proto, 10),
            status_is(StatusErrorCode::INVALID_ARGUMENT)
        )?;

        Ok(())
    }
